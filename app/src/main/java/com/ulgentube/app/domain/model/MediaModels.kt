package com.ulgentube.app.domain.model

/**
 * Desteklenen sosyal medya ve içerik platformları.
 */
enum class PlatformType(
    val displayName: String,
    val badgeColorHex: Long
) {
    YOUTUBE("YouTube", 0xFFFF0000),
    INSTAGRAM("Instagram", 0xFFE1306C),
    TIKTOK("TikTok", 0xFF00F2EA),
    TWITTER_X("X / Twitter", 0xFF1DA1F2),
    FACEBOOK("Facebook", 0xFF1877F2),
    REDDIT("Reddit", 0xFFFF4500),
    PINTEREST("Pinterest", 0xFFE60023),
    SOUNDCLOUD("SoundCloud", 0xFFFF5500),
    VIMEO("Vimeo", 0xFF1AB7EA),
    TWITCH("Twitch", 0xFF9146FF),
    KICK("Kick", 0xFF53FC18),
    DIRECT_IMAGE("Görsel", 0xFF10B981),
    OTHER("Web", 0xFF6366F1)
}

/**
 * İndirilecek medya kategorisi.
 */
enum class MediaCategory {
    VIDEO,
    AUDIO,
    IMAGE
}

/**
 * İndirme görevi durum yaşam döngüsü.
 */
enum class DownloadStatus {
    QUEUED,
    DOWNLOADING,
    PAUSED,
    MERGING,
    COMPLETED,
    FAILED,
    CANCELLED
}

/**
 * Uygulama tema tercihi.
 */
enum class ThemeMode {
    SYSTEM,
    DARK,
    LIGHT
}

/**
 * Kullanıcıya sunulan tek bir video veya ses kalite/format seçeneği.
 */
data class MediaFormatOption(
    val id: String,
    val label: String,
    val sublabel: String,
    val category: MediaCategory,
    val extension: String,
    val resolutionHeight: Int = 0,
    val bitrateKbps: Int = 0,
    val fps: Int = 0,
    val videoCodec: String? = null,
    val isHdrOrHighBit: Boolean = false,
    val badgeTags: List<String> = emptyList(),
    val transcodeTargetHeight: Int? = null,
    val fileSizeBytes: Long? = null,
    val ytDlpFormatSelector: String? = null,
    val directUrl: String? = null,
    val isAudioExtraction: Boolean = false
)

/**
 * Fotoğraf, galeri öğesi veya kapak görseli modeli.
 */
data class ImageItem(
    val id: String,
    val url: String,
    val label: String,
    val extension: String = "jpg",
    val width: Int? = null,
    val height: Int? = null
)

/**
 * Altyazı seçeneği modeli.
 */
data class SubtitleOption(
    val langCode: String,
    val label: String,
    val isAutoGenerated: Boolean = false,
    val downloadUrl: String? = null
)

/**
 * Çok dilli YouTube videoları için ses parçacığı (dublaj) seçeneği.
 */
data class AudioTrackOption(
    val id: String,
    val langCode: String,
    val label: String,
    val directUrl: String,
    val webmDirectUrl: String? = null,
    val isDefault: Boolean = false,
    val itag: Int = 0
)

/**
 * Oynatma listesi (playlist) içindeki tekil medya öğesi.
 */
data class PlaylistEntry(
    val id: String,
    val url: String,
    val title: String,
    val author: String? = null,
    val durationSeconds: Long? = null,
    val thumbnailUrl: String? = null
)

/**
 * FFmpeg Stüdyo hızlı medya dönüştürme eylemleri.
 */
enum class FfmpegStudioAction(
    val displayName: String,
    val description: String
) {
    EXTRACT_MP3("MP3'e Çevir", "320 kbps yüksek kalite ses"),
    COMPRESS_WHATSAPP("WhatsApp / Discord Sıkıştır", "720p optimize küçük boyut"),
    MAKE_GIF("GIF Oluştur", "Akıcı animasyon (FPS/Boyut ayarlı)"),
    REMOVE_AUDIO("Sesini Kaldır (Mute)", "Kalite kayıpsız sessiz video"),
    TRIM_VIDEO("Video Kırp (Trim)", "Başlangıç ve bitiş aralığını kes"),
    MERGE_VIDEOS("Videoları Birleştir", "Seçili klipleri tek videoda topla"),
    CONVERT_AUDIO("Ses Dönüştür / Zil Sesi", "M4A / FLAC / AAC / Zil Sesi kaydet"),
    CHANGE_SPEED("Oynatma Hızını Değiştir", "Kalıcı 0.5x – 4.0x hızlandır / yavaşlat"),
    CROP_ASPECT("En-Boy Kırp (Sosyal)", "9:16 Reels, 1:1 Kare, 16:9 Geniş")
}

enum class StudioAspectRatio(val label: String, val ratioW: Int, val ratioH: Int) {
    RATIO_9_16("9:16 Dikey (Reels/Shorts)", 9, 16),
    RATIO_1_1("1:1 Kare (Instagram)", 1, 1),
    RATIO_16_9("16:9 Yatay (YouTube)", 16, 9)
}

data class FfmpegStudioOptions(
    val trimStartSeconds: Float = 0f,
    val trimEndSeconds: Float = 0f,
    val audioFormat: String = "mp3",
    val saveAsRingtone: Boolean = false,
    val speedFactor: Float = 1.5f,
    val aspectRatio: StudioAspectRatio = StudioAspectRatio.RATIO_9_16,
    val gifFps: Int = 12,
    val gifMaxWidth: Int = 480,
    val useWebp: Boolean = false,
    val mergeSourceUris: List<String> = emptyList()
)

enum class EqualizerPreset(val displayName: String, val bandLevelsMb: List<Short>) {
    FLAT("Düz (Varsayılan)", listOf(0, 0, 0, 0, 0)),
    BASS_BOOST("Bas Güçlü", listOf(500, 350, 0, 100, 150)),
    VOCAL("Vokal / Podcast", listOf(-150, 100, 400, 350, 100)),
    TREBLE("Tiz / Akustik", listOf(0, 100, 200, 350, 450)),
    ROCK("Enerjik / Rock", listOf(350, 150, -100, 200, 350))
}

data class FollowedChannel(
    val channelId: String,
    val title: String,
    val url: String,
    val platform: PlatformType = PlatformType.YOUTUBE,
    val autoDownloadLatest: Boolean = false,
    val lastKnownVideoId: String? = null,
    val lastKnownVideoTitle: String? = null,
    val lastCheckedAt: Long = 0L,
    val createdAt: Long = System.currentTimeMillis()
)

/**
 * Bir URL analiz edildiğinde dönen birleşik medya bilgisi.
 */
data class ExtractedMedia(
    val originalUrl: String,
    val title: String,
    val author: String?,
    val durationSeconds: Long?,
    val thumbnailUrl: String?,
    val platform: PlatformType,
    val videoFormats: List<MediaFormatOption>,
    val audioFormats: List<MediaFormatOption>,
    val imageItems: List<ImageItem>,
    val subtitles: List<SubtitleOption> = emptyList(),
    val audioTracks: List<AudioTrackOption> = emptyList(),
    val isPlaylist: Boolean = false,
    val playlistEntries: List<PlaylistEntry> = emptyList()
)

/**
 * Veritabanında saklanan ve arka planda yürütülen indirme görevi.
 */
data class DownloadTask(
    val id: String,
    val url: String,
    val title: String,
    val author: String?,
    val thumbnailUrl: String?,
    val platform: PlatformType,
    val category: MediaCategory,
    val formatLabel: String,
    val fileName: String,
    val savedUri: String? = null,
    val savedPath: String? = null,
    val fileSizeBytes: Long = 0L,
    val progress: Float = 0f,
    val speedText: String? = null,
    val etaSeconds: Long? = null,
    val status: DownloadStatus = DownloadStatus.QUEUED,
    val errorMessage: String? = null,
    val ytDlpFormatSelector: String? = null,
    val directUrl: String? = null,
    val isAudioExtraction: Boolean = false,
    val transcodeTargetHeight: Int? = null,
    val targetExtension: String = "mp4",
    val createdAt: Long = System.currentTimeMillis(),
    val clipStartSeconds: Long? = null,
    val clipEndSeconds: Long? = null,
    val subtitleLang: String? = null,
    val embedSubtitles: Boolean = false,
    val lastPlaybackPositionMs: Long = 0L,
    val isFavorite: Boolean = false,
    val isInVault: Boolean = false,
    val lyricsText: String? = null
)

